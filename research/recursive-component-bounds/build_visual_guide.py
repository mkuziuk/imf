#!/usr/bin/env python3
"""Regenerate the visual guide's plot coordinates from the audited results.

Run from the repository root with .venv/bin/python. This does not rerun or
modify the numerical diagnostics. All figures are drawn as vectors in TeX.
"""

import csv
import json
from pathlib import Path

import numpy as np


HERE = Path(__file__).resolve().parent
OUTPUT = HERE.parents[1] / "overleaf/irmf_all_components_guide/plot_data.tex"


def coordinates(name, x_values, y_values):
    pairs = " ".join(f"({x:.8g},{y:.8g})" for x, y in zip(x_values, y_values))
    return rf"\def\{name}{{{pairs}}}" + "\n"


def main():
    data = json.loads((HERE / "diagnostics/verification.json").read_text())
    n = data["n"]
    product = np.ones(n)
    lines = ["% Generated by build_visual_guide.py; do not edit by hand.\n"]
    for stage, window in enumerate(data["windows"], 1):
        radius = window // 2
        offsets = np.arange(-radius, radius + 1)
        weights = (1 - np.abs(offsets / radius)) ** 2
        weights /= weights.sum()
        impulse = np.zeros(n)
        impulse[offsets % n] = weights
        multiplier = np.fft.fft(impulse).real
        if stage in [1, 3, 5, 7, 9]:
            name = {1: "One", 3: "Three", 5: "Five", 7: "Seven", 9: "Nine"}[stage]
            lines.append(coordinates("freq" + name, np.arange(41), (multiplier * product)[:41]))
        product *= 1 - multiplier

    with (HERE / "diagnostics/linear_partial_products.csv").open() as handle:
        rows = [row for row in csv.DictReader(handle) if row["kernel"] == "squared_triangle"]
    stages = np.arange(1, 10)
    lines.append(coordinates("residualNorm", stages, [float(row["prefix_linf"]) for row in rows]))
    lines.append(coordinates("componentNorm", stages, [float(row["prefix_component_linf"]) for row in rows]))
    for name, filename in [("mcGaussian", "leading_term_mc_gauss.npz"),
                           ("mcContaminated", "leading_term_mc_p0.2_s6.npz")]:
        ratios = data["submitted_results"][filename]["median_relative_sup_remainder"]
        lines.append(coordinates(name, stages, 100 * np.asarray(ratios)))
    OUTPUT.write_text("".join(lines))
    print(OUTPUT)


if __name__ == "__main__":
    main()
